export const readJson = (f) => JSON.parse(read(f));
export function write(f, text) { mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, text); }
export const exists = existsSync;
export const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);
export function walk(dir, filter = () => true, out = []) {
  if (!existsSync(dir)) return out;
  for (const n of readdirSync(dir)) {
    const f = join(dir, n);
    if (statSync(f).isDirectory()) { if (n === 'node_modules' || n === '.git') continue; walk(f, filter, out); }
    else if (filter(f)) out.push(f);
  }
  return out;
}
